local function groundAt(x, y, z, up, down)
	QueryRequire("physical large")
	rejectAll()
	local hit, dist = QueryRaycast(Vec(x, y + up, z), Vec(0, -1, 0), up + down)
	if hit then return y + up - dist end
	return nil
end

------------------------------------------------------------------------------------
-- assembly: place all 13 parts exactly, snap the feet onto the ground
------------------------------------------------------------------------------------
local function assemble()
	local pel = P.pelvis
	local t0 = GetBodyTransform(pel.body)
	local pivotPel = v3(pel.L.pivot)
	-- ground point below the pelvis of the freshly spawned prefab
	local O = VecSub(t0.pos, QuatRotateVec(t0.rot, pivotPel))

	-- face the player at spawn
	local rot0 = t0.rot
	local pp = GetPlayerTransform().pos
	local toPlayer, dist = flat(VecSub(pp, O))
	if dist > 1.0 then
		rot0 = QuatLookAt(Vec(0, 0, 0), toPlayer)
	end

	-- find the ground (spawn point may be slightly above / below the surface)
	local gy = nil
	for _, up in ipairs({3, 12, 40}) do
		gy = groundAt(O[1], O[2], O[3], up, 80)
		if gy then break end
	end
	if gy then O = Vec(O[1], gy + CFG.FOOT_CLEARANCE + 0.3, O[3]) end

	for _, name in ipairs(LAYOUT.order) do
		local p = P[name]
		local pos = VecAdd(O, QuatRotateVec(rot0, v3(p.L.pivot)))
		SetBodyTransform(p.body, Transform(pos, rot0))
		SetBodyVelocity(p.body, Vec(0, 0, 0))
		SetBodyAngularVelocity(p.body, Vec(0, 0, 0))
	end

	-- verify / correct shape placement (guards against a different vox pivot convention)
	local maxErr = 0
	for _, name in ipairs(LAYOUT.order) do
		local p = P[name]
		local bt = GetBodyTransform(p.body)
		local mi, ma = GetShapeBounds(p.shape)
		local actual = VecLerp(mi, ma, 0.5)
		local expected = VecAdd(bt.pos, QuatRotateVec(bt.rot, v3(p.L.center_off)))
		local delta = VecSub(expected, actual)
		local err = VecLength(delta)
		if err > maxErr then maxErr = err end
		if err > 0.25 and SetShapeLocalTransform and GetShapeLocalTransform then
			local lt = GetShapeLocalTransform(p.shape)
			local localShift = TransformToLocalVec(bt, delta)
			SetShapeLocalTransform(p.shape, Transform(VecAdd(lt.pos, localShift), lt.rot))
		end
		local sx, sy, sz = GetShapeSize(p.shape)
		local e = p.L.size
		if sx ~= e[1] or sy ~= e[2] or sz ~= e[3] then
			DebugPrint("[Titan] unexpected shape size for " .. name .. ": " .. tostring(sx) .. "," .. tostring(sy) .. "," .. tostring(sz) ..
				" expected " .. e[1] .. "," .. e[2] .. "," .. e[3])
		end
	end
	if maxErr > 0.25 then DebugPrint("[Titan] shape placement corrected, max error " .. string.format("%.2f", maxErr) .. " m") end

	-- feet exactly on the ground
	local minY = 1e9
	for _, name in ipairs({"footR", "footL"}) do
		local mi = GetShapeBounds(P[name].shape)
		if mi[2] < minY then minY = mi[2] end
	end
	if gy then
		local shift = (gy + CFG.FOOT_CLEARANCE) - minY
		for _, name in ipairs(LAYOUT.order) do
			local bt = GetBodyTransform(P[name].body)
			SetBodyTransform(P[name].body, Transform(VecAdd(bt.pos, Vec(0, shift, 0)), bt.rot))
		end
	end
end


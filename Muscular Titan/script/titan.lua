-- MUSCULAR TITAN
--
-- A giant walking enemy built from 13 voxel body parts (see titan.xml). Technique is
-- adapted from the King Kong reference mod (kong.lua / Teardown's robot script):
--   * the pelvis is the "robot body": it hovers over the ground on 4 down-rays, is held
--     upright, is turned and driven forward with ConstrainVelocity / ConstrainAngularVelocity
--   * every other body part is driven relative to the pelvis with ConstrainPosition /
--     ConstrainOrientation (like Kong's feet) - there are no joints, so nothing wobbles
--   * feet are planted on the ground and take alternating steps (Kong's feetUpdate idea);
--     the legs are solved with two-bone IK so planted feet never slide
--   * arms swing opposite to the legs, the chest twists / rolls with the steps, the head
--     stays stable
--
-- This file is generated by titan_tools/build_titan.py from titan_tools/titan.lua.tpl.
-- Change CFG below (or the param0/param1 values in titan.xml) to tune the titan.
------------------------------------------------------------------------------------


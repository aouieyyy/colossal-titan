local function obstacleUpdate(dt)
	-- walls in the way are cut open (like the reference's "breakall") so the titan never gets stuck
	R.smashTimer = R.smashTimer - dt
	R.breakTimer = math.max(0, R.breakTimer - dt)
	if R.speed < 0.5 then return end
	local fwd = flat(VecScale(R.axes[3], -1))
	local base = R.transform.pos
	local heights = {LAYOUT.ankleHeight + 3, hover.distTarget * 0.55, hover.distTarget * 0.95}
	for i = 1, #heights do
		local origin = VecAdd(Vec(base[1], base[2] - hover.distTarget + heights[i], base[3]), VecScale(fwd, 2.5))
		QueryRequire("physical")
		rejectAll()
		local hit, dist, normal, shape = QueryRaycast(origin, fwd, 7.0, 0.4)
		if hit then
			local b = GetShapeBody(shape)
			if b ~= 0 and not IsBodyDynamic(b) and R.blocked > 0.2 and R.smashTimer <= 0 then
				R.smashTimer = CFG.SMASH_INTERVAL
				local p = VecAdd(origin, VecScale(fwd, dist))
				local r = CFG.SMASH_RADIUS
				MakeHole(p, r, r, r, true)
			end
		end
	end
	if R.blocked > 0.3 then
		R.breakTimer = 0.2
	end
end

local function aiUpdate(dt)
	local pp = GetPlayerTransform().pos
	local toPlayer, dist = flat(VecSub(pp, R.transform.pos))
	R.distToPlayer = dist
	R.dir = toPlayer
	local fwd = flat(VecScale(R.axes[3], -1))
	local facing = VecDot(fwd, toPlayer)

	-- sidestep when it has been stuck for a while
	if R.sideStep > 0 then
		R.sideStep = R.sideStep - dt
		R.dir = flat(QuatRotateVec(QuatEuler(0, R.sideStepDir, 0), toPlayer))
	end

	local desired = 0
	if dist > CFG.STOP_DISTANCE then
		desired = CFG.SPEED * clamp((dist - CFG.STOP_DISTANCE) / math.max(1, CFG.SLOW_DISTANCE), 0.12, 1)
		if dist > CFG.DETECT_DISTANCE then desired = desired * CFG.FAR_SPEED_SCALE end
		local sc = clamp((facing - 0.1) / 0.9, 0, 1)
		desired = desired * math.max(CFG.MIN_TURN_SPEED_SCALE, sc)
	end
	R.speed = desired

	-- stuck detection: wants to move but does not
	local hv = GetBodyVelocity(R.body)
	local hspeed = VecLength(Vec(hv[1], 0, hv[3]))
	if desired > 1.0 and hspeed < desired * 0.15 and hover.contact > 0 then
		R.stuckTimer = R.stuckTimer + dt
	else
		R.stuckTimer = math.max(0, R.stuckTimer - dt * 2)
	end
	if R.stuckTimer > 4.0 and R.sideStep <= 0 then
		R.sideStep = 2.5
		R.sideStepDir = (math.random() < 0.5) and 70 or -70
		R.stuckTimer = 2.0
	end

	obstacleUpdate(dt)
	R.attackTimer = R.attackTimer - dt
end

------------------------------------------------------------------------------------
-- gait: planted feet, alternating steps, two-bone IK
------------------------------------------------------------------------------------
local function footRest(foot, pt, fwd, right, vfwd)
	local lead = clamp(vfwd * CFG.LEAD_TIME, -CFG.STEP_TRIGGER * 1.6, CFG.STEP_TRIGGER * 1.6)
	local p = VecAdd(pt.pos, VecAdd(VecScale(right, foot.side * foot.spread), VecScale(fwd, lead)))
	local y = groundAt(p[1], pt.pos[2], p[3], 4, hover.distTarget + 60)
	if not y then y = foot.P[2] end
	return Vec(p[1], y, p[3])
end

local function yawRot(fwd)
	return QuatLookAt(Vec(0, 0, 0), fwd)
end

local function gaitInit()
	local pt = GetBodyTransform(R.body)
	local fwd = flat(VecScale(TransformToParentVec(pt, Vec(0, 0, 1)), -1))
	for _, key in ipairs({"R", "L"}) do
		local fp = P["foot" .. key]
		local th = P["thigh" .. key]
		local foot = {
			key = key, side = (key == "R") and 1 or -1, part = fp,
			spread = math.abs(th.L.pivot[1] - P.pelvis.L.pivot[1]),
			stepping = false, t = 0, dur = CFG.STEP_TIME,
			lift = 0, attack = false,
		}
		local bt = GetBodyTransform(fp.body)
		local sole = VecSub(bt.pos, Vec(0, LAYOUT.ankleHeight + CFG.FOOT_CLEARANCE, 0))
		local gy = groundAt(sole[1], sole[2], sole[3], 6, 60)
		foot.P = Vec(sole[1], gy or sole[2], sole[3])
		foot.rot = yawRot(fwd)
		foot.from = VecCopy(foot.P)
		foot.to = VecCopy(foot.P)
		foot.rotFrom = foot.rot
		foot.rotTo = foot.rot
		foot.pos = VecCopy(foot.P)
		foot.curRot = foot.rot
		feet[key] = foot
	end
	gait.thighDir = {}
	gait.L1 = VecLength(v3(P.shinR.L.rel_parent))
	gait.L2 = VecLength(v3(P.footR.L.rel_parent))
end

local function startStep(foot, target, dur, height, attack)
	foot.stepping = true
	foot.t = 0
	foot.dur = dur
	foot.height = height
	foot.from = VecCopy(foot.pos)
	foot.to = target
	foot.rotFrom = foot.curRot
	foot.attack = attack or false
end

local function gaitUpdate(dt, pt, fwd, right, vfwd)
	local stepping = feet.R.stepping or feet.L.stepping
	-- plan
	if not stepping then
		local best, bestD, bestTarget = nil, 0, nil
		for _, key in ipairs({"R", "L"}) do
			local foot = feet[key]
			local rest = footRest(foot, pt, fwd, right, vfwd)
			local d = VecLength(Vec(foot.P[1] - rest[1], 0, foot.P[3] - rest[3]))
			if d > CFG.STEP_TRIGGER and d > bestD then
				best, bestD = foot, d
				local ahead = VecScale(fwd, math.max(0, vfwd) * CFG.STEP_TIME * 0.5)
				local tp = VecAdd(rest, ahead)
				local y = groundAt(tp[1], pt.pos[2], tp[3], 4, hover.distTarget + 60) or rest[2]
				bestTarget = Vec(tp[1], y, tp[3])
			end
		end
		if best then
			startStep(best, bestTarget, CFG.STEP_TIME, CFG.STEP_HEIGHT, false)
			best.rotTo = yawRot(fwd)
		elseif R.distToPlayer < CFG.ATTACK_RANGE and R.attackTimer <= 0 and R.speed < 0.5 then
			-- stomp at the player with the nearer foot
			local pp = GetPlayerTransform().pos
			local pick, pd = nil, 1e9
			for _, key in ipairs({"R", "L"}) do
				local foot = feet[key]
				local d = VecLength(Vec(foot.P[1] - pp[1], 0, foot.P[3] - pp[3]))
				if d < pd then pick, pd = foot, d end
			end
			local reach = (gait.L1 + gait.L2) * 0.7
			local hip = VecAdd(pt.pos, VecScale(right, pick.side * pick.spread))
			local off = Vec(pp[1] - hip[1], 0, pp[3] - hip[3])
			local l = VecLength(off)
			if l > reach then off = VecScale(off, reach / l) end
			local tp = VecAdd(hip, off)
			local y = groundAt(tp[1], pt.pos[2], tp[3], 4, hover.distTarget + 60) or pick.P[2]
			startStep(pick, Vec(tp[1], y, tp[3]), 1.1, CFG.STEP_HEIGHT * 1.8, true)
			pick.rotTo = yawRot(fwd)
			R.attackTimer = CFG.ATTACK_COOLDOWN
		end
	end

	-- animate
	for _, key in ipairs({"R", "L"}) do
		local foot = feet[key]
		if foot.stepping then
			foot.t = foot.t + dt
			local q = clamp(foot.t / foot.dur, 0, 1)
			local e = smooth(q)
			local p = VecLerp(foot.from, foot.to, e)
			foot.lift = math.sin(math.pi * q) * foot.height
			foot.pos = Vec(p[1], p[2] + foot.lift, p[3])
			local pitch = 0.3 * math.sin(math.pi * q) - 0.35 * math.max(0, 1 - 5 * q)
			local yaw = QuatSlerp(foot.rotFrom, foot.rotTo, e)
			foot.curRot = qMul(yaw, qAxis(Vec(1, 0, 0), pitch))
			if q >= 1 then
				foot.stepping = false
				foot.P = VecCopy(foot.to)
				foot.pos = VecCopy(foot.to)
				foot.rot = foot.rotTo
				foot.curRot = foot.rotTo
				foot.lift = 0
				gait.events[#gait.events + 1] = {pos = VecCopy(foot.to), attack = foot.attack}
				foot.attack = false
			end
		else
			foot.pos = VecCopy(foot.P)
			foot.curRot = foot.rot
			foot.lift = 0
		end
	end
end

-- two-bone IK: returns knee and (possibly clamped) ankle positions
local function solveLeg(hip, ankle, pole, L1, L2)
	local d = VecSub(ankle, hip)
	local dist = VecLength(d)
	if dist < 0.001 then d = Vec(0, -1, 0) dist = 0.001 end
	local u = VecScale(d, 1 / dist)
	local maxR = (L1 + L2) * 0.998
	local minR = math.abs(L1 - L2) * 1.002 + 0.05
	local c = clamp(dist, minR, maxR)
	local ank = VecAdd(hip, VecScale(u, c))
	local a = (L1 * L1 - L2 * L2 + c * c) / (2 * c)
	local h = math.sqrt(math.max(0, L1 * L1 - a * a))
	local pp = VecSub(pole, VecScale(u, VecDot(pole, u)))
	local pl = VecLength(pp)
	if pl < 0.0001 then
		pp = VecCross(u, Vec(1, 0, 0))
		pl = math.max(0.0001, VecLength(pp))
	end
	pp = VecScale(pp, 1 / pl)
	local knee = VecAdd(VecAdd(hip, VecScale(u, a)), VecScale(pp, h))
	return knee, ank
end

------------------------------------------------------------------------------------
-- pose: compute a target for every part and drive it with constraints
------------------------------------------------------------------------------------
local function drive(part, pos, rot)
	local t = GetBodyTransform(part.body)
	ConstrainPosition(part.body, R.body, t.pos, pos, CFG.LIMB_MAX_VEL, part.linForce)
	ConstrainOrientation(part.body, R.body, t.rot, rot, CFG.LIMB_MAX_ANGVEL, part.angForce)
end

local function partAlive(part)
	return not part.detached
end

poseOut = {}   -- last computed targets (for debugging / tests)

local function poseUpdate(dt, pt, fwd, right, vfwd)
	local Rp = pt.rot
	local up = Vec(0, 1, 0)
	local L1, L2 = gait.L1, gait.L2
	local thighSwing = {}
	local lifted = {}

	-- legs ------------------------------------------------------------------------
	local ankleUp = LAYOUT.ankleHeight + CFG.FOOT_CLEARANCE
	for _, key in ipairs({"R", "L"}) do
		local foot = feet[key]
		local th, sh, ft = P["thigh" .. key], P["shin" .. key], P["foot" .. key]
		local hip = VecAdd(pt.pos, QuatRotateVec(Rp, v3(th.L.rel_parent)))
		local ankleTarget = VecAdd(foot.pos, Vec(0, ankleUp, 0))
		local knee, ankle = solveLeg(hip, ankleTarget, fwd, L1, L2)

		local restThigh = VecNormalize(QuatRotateVec(Rp, v3(sh.L.rel_parent)))
		local newThigh = VecNormalize(VecSub(knee, hip))
		local thighRot = qMul(qFromTo(restThigh, newThigh), Rp)
		local restShin = VecNormalize(QuatRotateVec(Rp, v3(ft.L.rel_parent)))
		local newShin = VecNormalize(VecSub(ankle, knee))
		local shinRot = qMul(qFromTo(restShin, newShin), Rp)

		thighSwing[key] = math.atan2(VecDot(newThigh, fwd), -VecDot(newThigh, up))
		lifted[key] = foot.lift

		poseOut[th.name] = {hip, thighRot}
		poseOut[sh.name] = {knee, shinRot}
		poseOut[ft.name] = {ankle, foot.curRot}
	end

	-- chest: twist against the hips, lean forward, shift weight towards the planted foot
	local twist = clamp((thighSwing.R - thighSwing.L) * CFG.CHEST_TWIST, -0.12, 0.12)
	local roll = clamp((lifted.R - lifted.L) / math.max(0.5, CFG.STEP_HEIGHT) * CFG.CHEST_ROLL, -CFG.CHEST_ROLL, CFG.CHEST_ROLL)
	local lean = CFG.CHEST_LEAN * clamp(R.speed / math.max(0.1, CFG.SPEED), 0, 1)
	local chestAnim = qMul(qAxis(Vec(0, 1, 0), twist), qMul(qAxis(Vec(1, 0, 0), -lean), qAxis(Vec(0, 0, 1), roll)))
	local chestRot = qMul(Rp, chestAnim)
	local chestPos = VecAdd(pt.pos, QuatRotateVec(Rp, v3(P.chest.L.rel_parent)))
	poseOut.chest = {chestPos, chestRot}

	-- head: follows the chest position but keeps its orientation stable
	local headPos = VecAdd(chestPos, QuatRotateVec(chestRot, v3(P.head.L.rel_parent)))
	poseOut.head = {headPos, Rp}

	-- arms: swing opposite to the same-side thigh, restrained
	for _, key in ipairs({"R", "L"}) do
		local ua, fa = P["upperarm" .. key], P["forearm" .. key]
		local swing = clamp(-thighSwing[key] * CFG.ARM_SWING, -CFG.ARM_SWING_MAX, CFG.ARM_SWING_MAX)
		local shoulder = VecAdd(chestPos, QuatRotateVec(chestRot, v3(ua.L.rel_parent)))
		local uaRot = qMul(chestRot, qAxis(Vec(1, 0, 0), swing))
		local elbow = VecAdd(shoulder, QuatRotateVec(uaRot, v3(fa.L.rel_parent)))
		local bend = 0.10 + 0.45 * math.max(0, swing)
		local faRot = qMul(uaRot, qAxis(Vec(1, 0, 0), bend))
		poseOut[ua.name] = {shoulder, uaRot}
		poseOut[fa.name] = {elbow, faRot}
	end

	if R.dead then return end
	for _, name in ipairs(LAYOUT.order) do
		if name ~= "pelvis" and partAlive(P[name]) and poseOut[name] then
			drive(P[name], poseOut[name][1], poseOut[name][2])
		end
	end
end

------------------------------------------------------------------------------------
-- health / destruction
------------------------------------------------------------------------------------
-- All titan parts share collision layer 2 and ignore each other (they overlap at the joints);
-- they collide with the world and everything else. The filter is kept after a collapse on purpose:
-- switching self-collision on while the parts overlap would blow the wreck apart.
local function setOwnCollision(shape)
	SetShapeCollisionFilter(shape, 2, 253)
end

local function dieNow()
	if R.dead then return end
	R.dead = true
	for _, name in ipairs(LAYOUT.order) do
		local p = P[name]
		if IsHandleValid(p.body) then SetBodyDynamic(p.body, true) end
	end
	if sounds.death then PlaySound(sounds.death, R.transform.pos, 100.0) end
end

local function healthUpdate()
	local total0, total = 0, 0
	for _, name in ipairs(LAYOUT.order) do
		local p = P[name]
		total0 = total0 + p.voxels0
		local frac = 0
		if IsHandleValid(p.body) and IsHandleValid(p.shape) then
			frac = GetShapeVoxelCount(p.shape) / math.max(1, p.voxels0)
			total = total + GetShapeVoxelCount(p.shape)
		end
		if not p.detached and frac < CFG.LIMB_BREAK_FRACTION then
			p.detached = true
			if name:find("thigh") or name:find("shin") or name:find("foot") or name == "head" or name == "pelvis" or name == "chest" then
				dieNow()
			end
		end
	end
	R.integrity = total / math.max(1, total0)
	if R.integrity < CFG.COLLAPSE_FRACTION then dieNow() end
end

------------------------------------------------------------------------------------
-- init / update / tick
------------------------------------------------------------------------------------
function init()
	CFG.SPEED = GetFloatParam("speed", CFG.SPEED)
	CFG.TURN_SPEED = GetFloatParam("turnspeed", CFG.TURN_SPEED)

	for _, name in ipairs(LAYOUT.order) do
		local b = FindBody(name)
		if b == 0 then
			DebugPrint("[Titan] body '" .. name .. "' not found - titan disabled")
			return
		end
		local shapes = GetBodyShapes(b)
		if #shapes == 0 then
			DebugPrint("[Titan] body '" .. name .. "' has no shape - titan disabled")
			return
		end
		P[name] = {name = name, body = b, shape = shapes[1], L = LAYOUT.parts[name]}
		P[name].voxels0 = GetShapeVoxelCount(shapes[1])
		R.all[#R.all + 1] = b
	end
	R.body = P.pelvis.body

	sounds.step = LoadSound("robot/step-m0.ogg", 40.0)
	sounds.death = LoadSound("robot/disable0.ogg", 100.0)

	assemble()

	for _, name in ipairs(LAYOUT.order) do
		local p = P[name]
		local mass = GetBodyMass(p.body)
		p.linForce = 1e10 * math.max(1, mass)
		p.angForce = 1e10 * math.max(1, mass)
		setOwnCollision(p.shape)
		p.detached = false
	end

	robotSetAxes()
	hover.distTarget = LAYOUT.pelvisHeight * CFG.HIP_HEIGHT_FRACTION
	hover.distPadding = 2.0
	R.integrity = 1
	healthTimer = 0
	gaitInit()
	R.ready = true
end

function update(dt)
	if not R.ready or R.dead then return end
	robotUpdate(dt)
	aiUpdate(dt)
	hoverUpdate(dt)

	local pt = R.transform
	local fwd = flat(VecScale(R.axes[3], -1))
	local right = flat(R.axes[1])
	local vel = GetBodyVelocity(R.body)
	local vfwd = VecDot(vel, fwd)
	gaitUpdate(dt, pt, fwd, right, vfwd)
	poseUpdate(dt, pt, fwd, right, vfwd)

	-- let the titan break through whatever blocks it (same tag the reference robot uses)
	local want = R.breakTimer > 0
	if want ~= R.breaking then
		R.breaking = want
		for _, name in ipairs(LAYOUT.order) do
			local p = P[name]
			if IsHandleValid(p.shape) then
				if want then SetTag(p.shape, "breakall") else RemoveTag(p.shape, "breakall") end
			end
		end
	end
end

local function footfall(ev)
	local pp = GetPlayerTransform().pos
	local d = VecLength(VecSub(pp, ev.pos))
	if sounds.step then PlaySound(sounds.step, ev.pos, CFG.FOOTSTEP_VOLUME) end
	local shake = CFG.FOOTSTEP_SHAKE * clamp(1 - d / 220, 0, 1)
	if shake > 0.01 then ShakeCamera(shake) end

	ParticleReset()
	ParticleType("smoke")
	ParticleRadius(2.5, 6.0)
	ParticleColor(0.62, 0.57, 0.5)
	ParticleAlpha(0.6, 0.0)
	ParticleGravity(0.3)
	ParticleDrag(0.2)
	for i = 1, 4 do
		SpawnParticle(VecAdd(ev.pos, Vec((math.random() - 0.5) * 4, 0.5, (math.random() - 0.5) * 4)),
			Vec((math.random() - 0.5) * 6, 1 + math.random() * 2, (math.random() - 0.5) * 6), 2.5 + math.random() * 1.5)
	end

	local fp = CFG.FOOTPRINT
	if fp[1] > 0 then MakeHole(ev.pos, fp[1], fp[2], fp[3], true) end

	if d < CFG.STOMP_RADIUS and (ev.attack or d < CFG.STOMP_RADIUS * 0.5) then
		local h = GetPlayerHealth()
		if h > 0 then SetPlayerHealth(math.max(0, h - CFG.STOMP_DAMAGE)) end
	end
end

function tick(dt)
	if not R.ready then return end
	healthTimer = healthTimer + dt
	if healthTimer > 0.5 and not R.dead then
		healthTimer = 0
		healthUpdate()
	end
	for i = 1, #gait.events do
		footfall(gait.events[i])
	end
	gait.events = {}

	if CFG.DEBUG then
		for _, key in ipairs({"R", "L"}) do
			local f = feet[key]
			DebugLine(f.P, VecAdd(f.P, Vec(0, 6, 0)), 0, 1, 0)
		end
		DebugWatch("titan speed", R.speed)
		DebugWatch("titan integrity", R.integrity or 1)
		DebugWatch("titan contact", hover.contact)
	end
end

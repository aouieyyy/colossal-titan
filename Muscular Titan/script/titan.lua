------------------------------------------------------------------------------------
-- helpers
------------------------------------------------------------------------------------
local function clamp(v, a, b)
	if v < a then return a end
	if v > b then return b end
	return v
end

local function v3(t) return Vec(t[1], t[2], t[3]) end

local function flat(v)
	local r = Vec(v[1], 0, v[3])
	local l = VecLength(r)
	if l < 0.0001 then return Vec(0, 0, -1), 0 end
	return VecScale(r, 1 / l), l
end

local function smooth(q) return q * q * (3.0 - 2.0 * q) end

local function qAxis(axis, rad)
	local h = rad * 0.5
	local s = math.sin(h)
	return Quat(axis[1] * s, axis[2] * s, axis[3] * s, math.cos(h))
end

-- shortest rotation taking direction a to direction b (unit vectors)
local function qFromTo(a, b)
	local d = VecDot(a, b)
	if d > 0.999999 then return Quat(0, 0, 0, 1) end
	if d < -0.999999 then
		local ax = VecCross(a, Vec(1, 0, 0))
		if VecLength(ax) < 0.01 then ax = VecCross(a, Vec(0, 1, 0)) end
		return qAxis(VecNormalize(ax), math.pi)
	end
	local ax = VecNormalize(VecCross(a, b))
	return qAxis(ax, math.acos(d))
end

local function qMul(a, b) return QuatRotateQuat(a, b) end

local function rejectAll()
	for i = 1, #R.all do
		QueryRejectBody(R.all[i])
	end
end


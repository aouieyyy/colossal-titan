-- hover / upright / turn / move (adapted from kong.lua)
------------------------------------------------------------------------------------
local UPRIGHT_STRENGTH = 1.0
local UPRIGHT_MAX = 0.5
local UPRIGHT_BASE = 7

local function hoverFloat()
	if hover.contact > 0 then
		local d = clamp(hover.distTarget - hover.currentDist, -0.8, 0.8)
		local v = d * 4
		local f = hover.contact * math.max(0, d * R.mass * 5.0) + R.mass * 0.2
		ConstrainVelocity(R.body, hover.hitBody, R.bodyCenter, Vec(0, 1, 0), v, 0, f)
	end
end

local function hoverUpright()
	local up = VecCross(R.axes[2], Vec(0, 1, 0))
	local axes = {Vec(1, 0, 0), Vec(0, 1, 0), Vec(0, 0, 1)}
	for a = 1, 3, 2 do
		local d = VecDot(up, axes[a])
		local v = clamp(d * 15, -2, 2)
		local f = clamp(math.abs(d) * UPRIGHT_STRENGTH, -UPRIGHT_MAX, UPRIGHT_MAX)
		f = f + UPRIGHT_MAX * UPRIGHT_BASE
		f = f * R.mass * hover.contact
		ConstrainAngularVelocity(R.body, hover.hitBody, axes[a], v, -f, f)
	end
end

local function hoverTurn()
	local fwd = VecScale(R.axes[3], -1)
	local c = VecCross(fwd, R.dir)
	local d = VecDot(c, R.axes[2])
	local maxTurn = CFG.TURN_SPEED * R.speedScale
	local angVel = clamp(d * 10, -maxTurn, maxTurn)
	local curr = VecDot(R.axes[2], GetBodyAngularVelocity(R.body))
	angVel = curr + clamp(angVel - curr, -0.05 * R.speedScale, 0.05 * R.speedScale)
	local f = R.mass * 0.5 * hover.contact
	ConstrainAngularVelocity(R.body, hover.hitBody, R.axes[2], angVel, -f, f)
end

local function hoverMove()
	local desired = R.speed * R.speedScale
	local fwd = VecScale(R.axes[3], -1)
	fwd[2] = 0
	fwd = VecNormalize(fwd)
	local currSpeed = VecDot(fwd, GetBodyVelocityAtPos(R.body, R.bodyCenter))
	local speed = currSpeed + clamp(desired - currSpeed, -0.04 * R.speedScale, 0.04 * R.speedScale)
	local f = R.mass * 0.2 * hover.contact
	ConstrainVelocity(R.body, hover.hitBody, R.bodyCenter, fwd, speed, -f, f)
	ConstrainVelocity(R.body, hover.hitBody, R.bodyCenter, R.axes[1], 0, -f, f)
end

local function hoverUpdate(dt)
	local dir = VecScale(R.axes[2], -1)
	local hit = false
	local dist = 0
	local normal = Vec(0, 0, 0)
	local shape = 0
	local samples = {
		Vec(-BALANCE_RADIUS, 0, 0), Vec(BALANCE_RADIUS, 0, 0),
		Vec(0, 0, BALANCE_RADIUS), Vec(0, 0, -BALANCE_RADIUS),
	}
	local castRadius = 0.3
	local maxDist = hover.distTarget + hover.distPadding
	for i = 1, #samples do
		QueryRequire("physical large")
		rejectAll()
		local origin = TransformToParentPoint(R.transform, samples[i])
		local rhit, rdist, rnormal, rshape = QueryRaycast(origin, dir, maxDist, castRadius)
		if rhit then
			hit = true
			dist = dist + rdist + castRadius
			if rdist == 0 then rnormal = Vec(0, 1, 0) end
			if shape == 0 then
				shape = rshape
			else
				local b = GetShapeBody(rshape)
				local bb = GetShapeBody(shape)
				if not IsBodyDynamic(b) or (IsBodyDynamic(bb) and GetBodyMass(b) > GetBodyMass(bb)) then
					shape = rshape
				end
			end
			normal = VecAdd(normal, rnormal)
		else
			dist = dist + maxDist
		end
	end

	if hit then
		dist = dist / #samples
		normal = VecNormalize(normal)
		hover.hitBody = GetShapeBody(shape)
		if IsBodyDynamic(hover.hitBody) and GetBodyMass(hover.hitBody) < 300 then
			hover.hitBody = 0   -- small bodies are treated as static (like the reference)
		end
		hover.currentDist = dist
		hover.contact = clamp(1 - (dist - hover.distTarget) / hover.distPadding, 0.0, 10.0)
		hover.contact = hover.contact * math.max(0, normal[2])
	else
		hover.hitBody = 0
		hover.currentDist = maxDist
		hover.contact = 0
	end

	if hover.contact > 0 then
		hover.timeSinceContact = 0
	else
		hover.timeSinceContact = hover.timeSinceContact + dt
	end

	hoverFloat()
	hoverUpright()
	hoverTurn()
	hoverMove()
end


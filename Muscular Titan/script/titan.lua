local function robotSetAxes()
	R.transform = GetBodyTransform(R.body)
	R.axes[1] = TransformToParentVec(R.transform, Vec(1, 0, 0))
	R.axes[2] = TransformToParentVec(R.transform, Vec(0, 1, 0))
	R.axes[3] = TransformToParentVec(R.transform, Vec(0, 0, 1))
end

local function robotUpdate(dt)
	robotSetAxes()
	local vel = GetBodyVelocity(R.body)
	local fwdSpeed = VecDot(vel, R.dir)
	local blocked = 0
	if R.speed > 0 and fwdSpeed > -0.1 then
		blocked = 1.0 - clamp(fwdSpeed / 0.1, 0.0, 1.0)
	end
	R.blocked = R.blocked * 0.95 + blocked * 0.05

	R.mass = 0
	for i = 1, #R.all do
		if IsHandleValid(R.all[i]) then R.mass = R.mass + GetBodyMass(R.all[i]) end
	end
	R.bodyCenter = TransformToParentPoint(R.transform, GetBodyCenterOfMass(R.body))
end

